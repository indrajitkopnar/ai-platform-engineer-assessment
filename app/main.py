"""FastAPI service exposing both AI features behind one API.

Endpoints
  GET  /health          liveness + which LLM provider is configured
  POST /v1/classify     Scenario 1 — classify a support message
  POST /v1/chat         Scenario 2 — ask the engineering assistant
  GET  /docs            interactive Swagger UI (generated by FastAPI)

Both features share the same LLM gateway, configuration, logging and request tracing — the
"platform" part: a third AI feature would reuse all of it.
"""

from __future__ import annotations

import logging
import time
import uuid
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from pydantic import BaseModel, Field

from app.chatbot.service import ChatAnswer, ChatService
from app.classifier.service import ClassificationResult, TicketClassifier
from app.config import settings
from app.llm import get_llm

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")
logger = logging.getLogger("api")

services: dict[str, object] = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Load models and build the search index once at startup, not per request."""
    llm = get_llm()
    services["classifier"] = TicketClassifier(llm)
    services["chat"] = ChatService(llm)
    logger.info("Services ready (llm_provider=%s)", settings.llm_provider)
    yield
    services.clear()


app = FastAPI(title="AI Platform Engineer Assessment",
              description="Support-ticket classifier and engineering knowledge chatbot.",
              version="1.0.0", lifespan=lifespan)


@app.middleware("http")
async def request_tracing(request: Request, call_next):
    """Give every request an id (or keep the caller's) and log its latency — basic observability."""
    request_id = request.headers.get("x-request-id", uuid.uuid4().hex[:12])
    start = time.perf_counter()
    response = await call_next(request)
    response.headers["x-request-id"] = request_id
    logger.info("request_id=%s method=%s path=%s status=%s ms=%.1f", request_id, request.method,
                request.url.path, response.status_code, (time.perf_counter() - start) * 1000)
    return response


class ClassifyRequest(BaseModel):
    subject: str = Field("", max_length=300, examples=["Invoice charged twice"])
    body: str = Field(..., min_length=1, max_length=10_000,
                      examples=["Hi, we were charged twice for invoice 4471. Please refund the duplicate."])


class ChatRequest(BaseModel):
    question: str = Field(..., min_length=1, max_length=1000, examples=["What does alarm E104 mean?"])
    # In production the groups come from the user's SSO token, never from the request body.
    user_groups: list[str] = Field(default=["engineering"], examples=[["engineering"]])


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "llm_provider": settings.llm_provider}


@app.post("/v1/classify", response_model=ClassificationResult)
def classify(request: ClassifyRequest) -> ClassificationResult:
    return services["classifier"].classify(request.subject, request.body)


@app.post("/v1/chat", response_model=ChatAnswer)
def chat(request: ChatRequest) -> ChatAnswer:
    return services["chat"].ask(request.question, set(request.user_groups))
